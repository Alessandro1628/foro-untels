BEGIN;
CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(120) NOT NULL,
    email varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'USER',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_folded ON public.users (lower(email));
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS academic_program varchar(120);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS biography varchar(500);
