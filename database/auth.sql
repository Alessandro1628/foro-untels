BEGIN;
CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(120) NOT NULL,
    email varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'USER',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_folded ON public.users (lower(email));
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS academic_program varchar(120);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS biography varchar(500);
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_digest varchar(64);
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_requested timestamptz;
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_sent timestamptz;
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version integer NOT NULL DEFAULT 0;
CREATE UNIQUE INDEX IF NOT EXISTS unused_reset_digest ON users(reset_digest) WHERE reset_digest IS NOT NULL;
CREATE TABLE IF NOT EXISTS moderator_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor bigint NOT NULL REFERENCES users(id),
 account bigint NOT NULL REFERENCES users(id), granted boolean NOT NULL, changed_at timestamptz DEFAULT now()
);
DO $$
BEGIN
 IF EXISTS (SELECT FROM pg_roles WHERE rolname='auth_app') THEN
  GRANT INSERT ON moderator_history TO auth_app;
  GRANT USAGE ON SEQUENCE moderator_history_id_seq TO auth_app;
 END IF;
END $$;
COMMIT;
