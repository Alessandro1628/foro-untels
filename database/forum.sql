BEGIN;
CREATE TABLE IF NOT EXISTS public.posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL,
    title varchar(180) NOT NULL,
    content text NOT NULL,
    category varchar(80) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PUBLISHED',
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    updated_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE TABLE IF NOT EXISTS public.comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL REFERENCES public.posts(id),
    author_id bigint NOT NULL,
    content text NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PUBLISHED',
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    updated_at timestamptz NOT NULL DEFAULT current_timestamp
);
ALTER TABLE public.posts ADD COLUMN IF NOT EXISTS withdrawn_at timestamptz;
ALTER TABLE public.posts ADD COLUMN IF NOT EXISTS moderated_at timestamptz;
ALTER TABLE public.comments ADD COLUMN IF NOT EXISTS withdrawn_at timestamptz;
ALTER TABLE public.comments ADD COLUMN IF NOT EXISTS moderated_at timestamptz;
ALTER TABLE public.comments ADD COLUMN IF NOT EXISTS book_id varchar(64);
ALTER TABLE public.comments ADD COLUMN IF NOT EXISTS book_title text;
CREATE INDEX IF NOT EXISTS comments_thread_order ON public.comments(post_id, created_at, id);
CREATE TABLE IF NOT EXISTS public.reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL REFERENCES public.posts(id),
    comment_id bigint REFERENCES public.comments(id),
    reporter_id bigint NOT NULL, reason varchar(500) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    resolved_by bigint, decision_reason varchar(500), resolved_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.communities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
