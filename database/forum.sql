CREATE TABLE IF NOT EXISTS community_proposals (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL, purpose varchar(500) NOT NULL,
 proposer bigint NOT NULL, status text NOT NULL DEFAULT 'PENDING', reviewer bigint
);
CREATE UNIQUE INDEX IF NOT EXISTS pending_community_name ON community_proposals(lower(name)) WHERE status='PENDING';
CREATE UNIQUE INDEX IF NOT EXISTS community_name_ci ON communities(lower(name));
CREATE TABLE IF NOT EXISTS follows (user_id bigint NOT NULL, community_id bigint REFERENCES communities(id), PRIMARY KEY(user_id,community_id));
CREATE TABLE IF NOT EXISTS favorites (user_id bigint NOT NULL, post_id bigint REFERENCES posts(id), PRIMARY KEY(user_id,post_id));
CREATE TABLE IF NOT EXISTS useful_votes (user_id bigint NOT NULL, post_id bigint REFERENCES posts(id), PRIMARY KEY(post_id,user_id));
CREATE TABLE IF NOT EXISTS categories (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(80) NOT NULL, active boolean NOT NULL DEFAULT true);
CREATE UNIQUE INDEX IF NOT EXISTS category_name_ci ON categories(lower(name));
