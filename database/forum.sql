CREATE TABLE IF NOT EXISTS subjects (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL, active boolean NOT NULL DEFAULT true);
CREATE UNIQUE INDEX IF NOT EXISTS subject_name_ci ON subjects(lower(name));
CREATE TABLE IF NOT EXISTS credentials (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account bigint NOT NULL, full_name varchar(120) NOT NULL,
 kind text NOT NULL CHECK (kind IN ('TUTOR','TEACHER')), subject_id bigint REFERENCES subjects(id),
 evidence varchar(1500) NOT NULL, status text NOT NULL DEFAULT 'PENDING', reviewer bigint,
 CHECK ((kind='TUTOR') = (subject_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS current_credential ON credentials(account,kind,coalesce(subject_id,0)) WHERE status IN ('PENDING','APPROVED');
CREATE TABLE IF NOT EXISTS materials (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id bigint NOT NULL, shared_by varchar(120) NOT NULL,
 subject_id bigint NOT NULL REFERENCES subjects(id), title varchar(180) NOT NULL, author varchar(160) NOT NULL,
 kind text NOT NULL CHECK (kind IN ('PDF','LINK')), url text, document bytea, status text NOT NULL DEFAULT 'PENDING',
 version integer NOT NULL DEFAULT 1, observation varchar(500), reviewer bigint,
 CHECK ((kind='PDF' AND document IS NOT NULL AND url IS NULL) OR (kind='LINK' AND url IS NOT NULL AND document IS NULL))
);
CREATE TABLE IF NOT EXISTS material_reviews (
 material_id bigint REFERENCES materials(id), version integer NOT NULL, reviewer bigint NOT NULL,
 decision text NOT NULL, reason varchar(500), PRIMARY KEY(material_id,version)
);
CREATE TABLE IF NOT EXISTS tutoring_slots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, credential_id bigint NOT NULL REFERENCES credentials(id),
 tutor_id bigint NOT NULL, tutor_email varchar(255) NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL,
 student_id bigint, student_email varchar(255), rating integer CHECK (rating BETWEEN 1 AND 5),
 calendar_id uuid NOT NULL DEFAULT gen_random_uuid(), meet_url text, sync_state text NOT NULL DEFAULT 'PENDING',
 CHECK (ends_at>starts_at), UNIQUE(tutor_id,starts_at)
);
ALTER TABLE tutoring_slots ADD COLUMN IF NOT EXISTS next_sync timestamptz NOT NULL DEFAULT now();
DO $$
BEGIN
 IF EXISTS (SELECT FROM pg_roles WHERE rolname='forum_app') THEN
  GRANT SELECT, INSERT, UPDATE, DELETE ON communities, community_proposals, follows, favorites, useful_votes, categories,
   subjects, credentials, materials, material_reviews, tutoring_slots TO forum_app;
  GRANT USAGE ON SEQUENCE communities_id_seq, community_proposals_id_seq, categories_id_seq,
   subjects_id_seq, credentials_id_seq, materials_id_seq, tutoring_slots_id_seq TO forum_app;
 END IF;
END $$;
COMMIT;
